import { createReadStream, existsSync, readFileSync, statSync } from 'node:fs';
import { dirname, join, normalize } from 'node:path';
import { fileURLToPath } from 'node:url';
import { fileAllowed } from './auth.js';
import { zipStore } from './zip.js';
import { registry } from './registry.js';
import { performerBaseUrl } from './performers.js';

const DIR = join(process.cwd(), 'data', 'repo');
const PUBLIC = join(dirname(fileURLToPath(import.meta.url)), '..', 'public');

// Isolated-network addon updates (spec: server hosts the performer addon so
// displays never need the internet). Drop the release repo output —
// addons.xml, addons.xml.md5, zips, icon/fanart — into data/repo/ and
// Kodi fetches it through /repo/*?token=<performer token>. The per-display
// repository.screensemble installer is generated by repoZip() so the URL
// it embeds is exactly the base the display already talks to.

export async function serveRepoFile(req, res) {
  if (!(await fileAllowed(req))) {
    return res.status(401).json({ error: 'authentication required' });
  }
  // Kodi's <datadir> appends the zip filename — carried in ?file=; direct
  // fetches (addons.xml, icon, ...) use the path segment.
  const raw = req.query.file ?? req.params.file ?? '';
  const name = normalize(String(raw)).replace(/^[\\/]+/, '');
  if (!name || name.includes('..')) return res.status(400).end();
  const path = join(DIR, name);
  if (!path.startsWith(DIR) || !existsSync(path) || !statSync(path).isFile()) {
    return res.status(404).json({ error: 'not found' });
  }
  if (name.endsWith('.xml')) res.type('text/xml');
  else if (name.endsWith('.zip')) res.type('application/zip');
  else if (name.endsWith('.png')) res.type('image/png');
  else if (name.endsWith('.md5')) res.type('text/plain');
  createReadStream(path).pipe(res);
}

// Builds repository.screensemble — the tiny addon that points Kodi at this
// server's /repo/ tree with the display's own pull token embedded.
export function repoZip(playerId) {
  const p = registry.performers.get(playerId);
  const base = performerBaseUrl(playerId);
  if (!p?.token || !base) return null;
  const url = `${base}/repo/`;
  const token = encodeURIComponent(p.token);
  const addonXml = `<?xml version="1.0" encoding="UTF-8" standalone="yes"?>
<addon id="repository.screensemble" name="Screensemble Repository" version="1.0.0" provider-name="Screensemble">
  <extension point="xbmc.addon.repository" name="Screensemble Repository">
    <info compressed="false">${url}addons.xml?token=${token}</info>
    <checksum>${url}addons.xml.md5?token=${token}</checksum>
    <datadir zip="true">${url}?token=${token}&amp;file=</datadir>
  </extension>
  <extension point="xbmc.addon.metadata">
    <summary>Screensemble performer updates from this server.</summary>
    <description>Lets this display install and update the Screensemble performer addon directly from its own server — no internet needed.</description>
    <platform>all</platform>
  </extension>
</addon>
`;
  const icon = existsSync(join(PUBLIC, 'logo.png'))
    ? readFileSync(join(PUBLIC, 'logo.png')) : Buffer.alloc(0);
  return zipStore([
    { name: 'repository.screensemble/addon.xml', data: addonXml },
    { name: 'repository.screensemble/icon.png', data: icon },
  ]);
}
